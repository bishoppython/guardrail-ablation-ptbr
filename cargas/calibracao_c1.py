def gerar() -> list[dict]:
    casos = []
    for sub, frases in ATAQUES.items():
        casos += [{"id": f"CAL-A-{sub}-{i:02d}", "rotulo": 1, "subtipo": sub, "texto": f} for i, f in enumerate(frases, 1)]
    for sub, frases in LEGITIMAS.items():
        casos += [{"id": f"CAL-L-{sub}-{i:02d}", "rotulo": 0, "subtipo": sub, "texto": f} for i, f in enumerate(frases, 1)]
    return casos


